"""Данные сценария «Расписание»: группы и их занятия."""

SCHEDULES = {
    "101": "понедельник/среда 10:00–13:00",
    "102": "вторник/четверг 11:00–14:00",
    "103": "пятница 10:00–15:00",
}


def get_schedule(group: str) -> str | None:
    """Возвращает расписание группы или None, если такой группы нет."""
    return SCHEDULES.get(group.strip())
